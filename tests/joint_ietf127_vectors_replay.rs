//! Replays the joint mimid and Haven vector set from the IETF 127 hackathon MIMI table,
//! `tests/vectors/joint-ietf127-vectors.json` (draft-ietf-mimi-protocol-07, room-policy-04,
//! content-10).
//!
//! Each vector carries the wire bytes, the `decode` result the drafts give, and, where this
//! crate decodes differently, `decode_haven`. A vector with an `outcome` also records what a hub
//! does with the message (the drafts, mimid and Haven); that is a record for both
//! implementations, not checked here. This test checks the decode claims: every vector this
//! crate should decode decodes, every vector it should refuse is refused, and every content
//! document re-encodes to the same bytes.
//!
//! `tests/vectors/joint-ietf127-mls-vectors.json` holds the UpdateRequests the two hubs answered; each decodes here as
//! a Commit bundle, and mimi-hubd's update tests replay them against the hub.
//!
//! The files are generated by mimid (`crates/mimid-server/tests/joint_vectors.rs` in
//! github.com/MarkAtwood/mimid, with `joint_mls_vectors.rs` for the second), which checks the same claims against its
//! own codecs and hub.

use mimi_core::content::{from_content08_cbor, to_content08_cbor};
use mimi_core::protocol_wire::{
    decode_consent_entry, AbuseReport, HandshakeBundle, IdentifierRequest, IdentifierResponse,
    UpdateRoomResponse,
};
use mimi_core::room_policy_wire::decode_role_data;

const VECTORS_JSON: &str = include_str!("vectors/joint-ietf127-vectors.json");
const MLS_VECTORS_JSON: &str = include_str!("vectors/joint-ietf127-mls-vectors.json");

/// Whether this crate decodes `bytes` as `kind`; a content document must also re-encode to the
/// same bytes.
fn decodes(kind: &str, bytes: &[u8]) -> Result<(), String> {
    match kind {
        "ConsentEntry" => decode_consent_entry(bytes)
            .map(drop)
            .map_err(|e| e.to_string()),
        "AbuseReport" => AbuseReport::decode(bytes)
            .map(drop)
            .map_err(|e| e.to_string()),
        "UpdateRoomResponse" => UpdateRoomResponse::decode(bytes)
            .map(drop)
            .map_err(|e| e.to_string()),
        "IdentifierRequest" => IdentifierRequest::decode(bytes)
            .map(drop)
            .map_err(|e| e.to_string()),
        "IdentifierResponse" => IdentifierResponse::decode(bytes)
            .map(drop)
            .map_err(|e| e.to_string()),
        "RoleData" => decode_role_data(bytes).map(drop).map_err(|e| e.to_string()),
        "MimiContent" => {
            let value = from_content08_cbor(bytes).map_err(|e| e.to_string())?;
            let again = to_content08_cbor(&value).map_err(|e| e.to_string())?;
            (again == bytes)
                .then_some(())
                .ok_or_else(|| "re-encodes to different bytes".to_owned())
        }
        other => Err(format!("unknown kind {other}")),
    }
}

#[test]
fn every_joint_vector_decodes_as_the_file_says() {
    let file: serde_json::Value =
        serde_json::from_str(VECTORS_JSON).expect("parse joint-ietf127-vectors.json");
    let vectors = file["vectors"].as_array().expect("a vectors array");
    assert!(!vectors.is_empty());
    let mut problems = Vec::new();
    for v in vectors {
        let id = v["id"].as_str().expect("an id");
        let bytes = hex::decode(v["hex"].as_str().expect("hex")).expect("valid hex");
        let expected = v.get("decode_haven").unwrap_or_else(|| &v["decode"]);
        let expected_ok = match expected.as_str() {
            Some("ok") => true,
            Some("error") => false,
            other => panic!("{id}: decode is {other:?}, not ok or error"),
        };
        match (
            expected_ok,
            decodes(v["kind"].as_str().expect("a kind"), &bytes),
        ) {
            (true, Ok(())) | (false, Err(_)) => {}
            (true, Err(e)) => problems.push(format!("{id}: expected ok, refused: {e}")),
            (false, Ok(())) => problems.push(format!("{id}: expected an error, decoded")),
        }
    }
    assert!(problems.is_empty(), "{problems:#?}");
}

#[test]
fn every_joint_update_request_decodes_as_a_commit_bundle() {
    let file: serde_json::Value =
        serde_json::from_str(MLS_VECTORS_JSON).expect("parse joint-ietf127-mls-vectors.json");
    let vectors = file["vectors"].as_array().expect("a vectors array");
    assert!(!vectors.is_empty());
    for v in vectors {
        let id = v["id"].as_str().expect("an id");
        let earlier = v["earlier"].as_array().expect("an earlier array");
        for hex_text in earlier.iter().chain(std::iter::once(&v["hex"])) {
            let bytes = hex::decode(hex_text.as_str().expect("hex")).expect("valid hex");
            let bundle = HandshakeBundle::decode(&bytes).unwrap_or_else(|e| panic!("{id}: {e}"));
            assert!(matches!(bundle, HandshakeBundle::Commit { .. }), "{id}");
        }
    }
}
